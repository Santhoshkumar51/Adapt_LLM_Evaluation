"""
Pydantic schemas for all AdaptEval API request and response payloads.
Defines the contract between the React frontend and FastAPI backend.
"""

from enum import Enum
from typing import Dict, List, Optional
from pydantic import BaseModel, Field


# ── Supported base models ─────────────────────────────────────────────────────

class SupportedModel(str, Enum):
    """
    Enumeration of base models supported by AdaptEval.
    Only models that fit on a single T4 GPU with 4-bit QLoRA are included.
    """
    MISTRAL_7B = "mistralai/Mistral-7B-v0.1"
    LLAMA3_8B  = "meta-llama/Meta-Llama-3-8B"
    QWEN2_7B   = "Qwen/Qwen2-7B"


# ── Model list response ───────────────────────────────────────────────────────

class ModelInfo(BaseModel):
    """Metadata for a single supported base model."""
    model_id:    str  = Field(..., description="Hugging Face model ID")
    display_name: str = Field(..., description="Human-readable model name for UI dropdown")
    parameters:  str  = Field(..., description="Approximate parameter count e.g. '7B'")
    description: str  = Field(..., description="One-line model description")


class ModelsResponse(BaseModel):
    """Response schema for GET /api/models."""
    models: List[ModelInfo]


# ── Fine-tuning job ───────────────────────────────────────────────────────────

class JobStatus(str, Enum):
    """Lifecycle states of a fine-tuning job."""
    QUEUED     = "queued"
    PREPARING  = "preparing"
    TRAINING   = "training"
    EVALUATING = "evaluating"
    COMPLETE   = "complete"
    FAILED     = "failed"


class FinetuneRequest(BaseModel):
    """
    Request body for POST /api/finetune.
    Training data is sent as a file upload (multipart/form-data),
    not in this schema — see the route handler.
    """
    model_id: SupportedModel = Field(
        ...,
        description="Hugging Face model ID selected by the user.",
    )


class FinetuneJobResponse(BaseModel):
    """Initial response returned immediately when a fine-tuning job is accepted."""
    job_id:  str       = Field(..., description="UUID identifying this fine-tuning run")
    status:  JobStatus = Field(..., description="Initial job status")
    message: str       = Field(..., description="Human-readable status message")


# ── Job status polling ────────────────────────────────────────────────────────

class TrainingProgress(BaseModel):
    """Training loop progress snapshot."""
    current_epoch: int   = Field(..., description="Current training epoch")
    total_epochs:  int   = Field(..., description="Total training epochs configured")
    train_loss:    float = Field(..., description="Latest training loss value")
    eval_loss:     float = Field(..., description="Latest validation loss value")
    elapsed_mins:  float = Field(..., description="Elapsed training time in minutes")


class StatusResponse(BaseModel):
    """Response schema for GET /api/results/{job_id}/status."""
    job_id:   str                      = Field(..., description="Job UUID")
    status:   JobStatus                = Field(..., description="Current job lifecycle state")
    progress: Optional[TrainingProgress] = Field(None, description="Training progress if in TRAINING state")
    error:    Optional[str]            = Field(None, description="Error message if status is FAILED")


# ── Evaluation results ────────────────────────────────────────────────────────

class ModelMetrics(BaseModel):
    """Evaluation metrics for a single model (baseline or fine-tuned)."""
    accuracy:   float = Field(..., description="Classification accuracy on held-out test set")
    f1:         float = Field(..., description="Macro F1-score on held-out test set")
    perplexity: float = Field(..., description="Mean perplexity on held-out test set")


class ImprovementMetrics(BaseModel):
    """Delta metrics — fine-tuned minus baseline for each metric."""
    accuracy_delta:   float = Field(..., description="Accuracy improvement (fine-tuned - baseline)")
    f1_delta:         float = Field(..., description="F1 improvement (fine-tuned - baseline)")
    perplexity_delta: float = Field(..., description="Perplexity reduction (baseline - fine-tuned)")


class SamplePrediction(BaseModel):
    """A single side-by-side sample output comparison."""
    input:            str = Field(..., description="Input prompt shown to both models")
    baseline_output:  str = Field(..., description="Response generated by baseline model")
    finetuned_output: str = Field(..., description="Response generated by fine-tuned model")
    reference:        str = Field(..., description="Ground-truth reference response")


class AdapterInfo(BaseModel):
    """Metadata about the saved adapter weights file."""
    size_mb:      float = Field(..., description="Adapter file size in megabytes")
    trained_params_pct: float = Field(..., description="% of total model parameters that were trained")
    training_time_mins: float = Field(..., description="Total fine-tuning time in minutes")


class ResultsResponse(BaseModel):
    """
    Full evaluation results returned by GET /api/results/{job_id}.
    Powers the entire dashboard — KPIs, sample outputs, adapter info.
    """
    job_id:      str                    = Field(..., description="Job UUID")
    model_id:    str                    = Field(..., description="Base model used for this run")
    baseline:    ModelMetrics           = Field(..., description="Baseline model evaluation metrics")
    finetuned:   ModelMetrics           = Field(..., description="Fine-tuned model evaluation metrics")
    improvement: ImprovementMetrics     = Field(..., description="Delta metrics")
    samples:     List[SamplePrediction] = Field(..., description="Sample side-by-side predictions")
    adapter:     AdapterInfo            = Field(..., description="Adapter weights metadata")